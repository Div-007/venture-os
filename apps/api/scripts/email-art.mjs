// Generates the dithered email artwork (ordered Bayer dither, like the web app) and writes it as base64 constants to
// src/email/art.ts, so emails can embed the images inline (cid:) without depending on the website being up.
// Run: node scripts/email-art.mjs   (from apps/api)
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const BAYER = [0, 32, 8, 40, 2, 34, 10, 42, 48, 16, 56, 24, 50, 18, 58, 26, 12, 44, 4, 36, 14, 46, 6, 38, 60, 28, 52, 20, 62, 30, 54, 22, 3, 35, 11, 43, 1, 33, 9, 41, 51, 19, 59, 27, 49, 17, 57, 25, 15, 47, 7, 39, 13, 45, 5, 37, 63, 31, 55, 23, 61, 29, 53, 21].map((value) => (value + 0.5) / 64);

/** A dithered field: `strength(u, v)` in 0..1 picks a palette step through the Bayer threshold. Upscaled with crisp pixels. */
async function dither({ cols, rows, scale, base, palette, strength }) {
  const raw = Buffer.alloc(cols * rows * 3);
  for (let y = 0; y < rows; y++) for (let x = 0; x < cols; x++) {
    const level = Math.min(1, Math.max(0, strength(x / cols, y / rows))) * palette.length;
    const index = Math.floor(level) + (level % 1 > BAYER[(y % 8) * 8 + (x % 8)] ? 1 : 0);
    const color = index > 0 ? palette[Math.min(index, palette.length) - 1] : base;
    raw.set(color, (y * cols + x) * 3);
  }
  return sharp(raw, { raw: { width: cols, height: rows, channels: 3 } }).resize(cols * scale, rows * scale, { kernel: "nearest" }).png({ compressionLevel: 9, palette: true }).toBuffer();
}

// Hero banner: deep green, brightest in the top-right corner. 600x200 at 2x.
const hero = await dither({ cols: 200, rows: 66, scale: 6, base: [15, 61, 36], palette: [[21, 86, 51], [29, 118, 68], [46, 160, 94], [104, 210, 148]],
  strength: (u, v) => Math.max(0, 1 - Math.hypot((u - 0.95) * 2.1, (v + 0.15) * 1.15)) ** 1.2 });
// Button texture: green with light pixels gathering toward the right. 280x56 at 2x.
const button = await dither({ cols: 140, rows: 28, scale: 4, base: [23, 122, 61], palette: [[30, 140, 72], [44, 164, 92], [84, 196, 130]],
  strength: (u, v) => (u * 0.95 + (1 - Math.abs(v - 0.5) * 2) * 0.08) ** 1.6 });
// The brand mark (apps/web/public/brand/logo-mark.png), used in the email header and footer.
const brand = (name) => fileURLToPath(new URL(`../../web/public/brand/${name}`, import.meta.url));
const logo = await sharp(brand("logo-mark.png")).resize(80, 80, { kernel: "lanczos3" }).png({ compressionLevel: 9 }).toBuffer();

const out = fileURLToPath(new URL("../src/email/art.ts", import.meta.url));
fs.writeFileSync(out, `// Generated by scripts/email-art.mjs. Do not edit by hand.\n/** Dithered email artwork, embedded inline (cid:) so emails render even when the website is unreachable. */\nexport const EMAIL_ART = {\n  hero: "${hero.toString("base64")}",\n  button: "${button.toString("base64")}",\n  logo: "${logo.toString("base64")}",\n} as const;\n`);
console.log(`hero ${(hero.length / 1024).toFixed(1)} KB, button ${(button.length / 1024).toFixed(1)} KB, logo ${(logo.length / 1024).toFixed(1)} KB -> ${out}`);
